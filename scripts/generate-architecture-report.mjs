#!/usr/bin/env node
// Regenerates ARCHITECTURE_AUTO_GENERATED.md from the real source tree.
//
//   node scripts/generate-architecture-report.mjs
//
// The file is committed, so it must never be edited by hand: change the
// source layout and re-run `npm run docs:arch`.

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = process.cwd();
const SRC = join(ROOT, 'src');
const OUTPUT = join(ROOT, 'ARCHITECTURE_AUTO_GENERATED.md');

const CODE_EXTENSIONS = new Set(['.ts', '.tsx', '.js', '.jsx', '.mjs']);
const STYLE_EXTENSIONS = new Set(['.css']);
const IGNORED_DIRS = new Set(['node_modules', 'dist', 'build', 'coverage', '.git']);
const IGNORED_FILES = new Set(['vite-env.d.ts']);

function extensionOf(path) {
  const index = path.lastIndexOf('.');
  return index === -1 ? '' : path.slice(index);
}

function listFiles(dir) {
  const entries = [];

  for (const name of readdirSync(dir).sort()) {
    if (IGNORED_DIRS.has(name)) continue;
    const absolute = join(dir, name);
    if (statSync(absolute).isDirectory()) {
      entries.push(...listFiles(absolute));
    } else if (!IGNORED_FILES.has(name)) {
      entries.push(absolute);
    }
  }

  return entries;
}

function countLines(path) {
  return readFileSync(path, 'utf8')
    .split('\n')
    .filter(line => line.trim().length > 0).length;
}

function groupByDirectory(files) {
  const groups = new Map();

  for (const file of files) {
    const dir = relative(ROOT, file).split(/[\\/]/).slice(0, -1).join('/');
    groups.set(dir, (groups.get(dir) ?? 0) + 1);
  }

  return [...groups.entries()].sort(([a], [b]) => a.localeCompare(b));
}

function renderTree(files) {
  const root = { name: 'src', children: new Map() };

  for (const file of files) {
    const parts = relative(SRC, file).split(/[\\/]/);
    let node = root;
    for (let i = 0; i < parts.length - 1; i++) {
      if (!node.children.has(parts[i])) node.children.set(parts[i], { name: parts[i], children: new Map() });
      node = node.children.get(parts[i]);
    }
    node.children.set(parts[parts.length - 1], { name: parts[parts.length - 1], children: null });
  }

  const lines = [];

  const walk = (node, prefix) => {
    const children = [...node.children.values()];
    children.forEach((child, index) => {
      const isLast = index === children.length - 1;
      lines.push(`${prefix}${isLast ? '└── ' : '├── '}${child.name}${child.children ? '/' : ''}`);
      if (child.children) walk(child, `${prefix}${isLast ? '    ' : '│   '}`);
    });
  };

  lines.push('src/');
  walk(root, '');
  return lines.join('\n');
}

function readPackage() {
  const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
  return {
    version: pkg.version,
    dependencies: Object.keys(pkg.dependencies ?? {}).sort(),
    devDependencies: Object.keys(pkg.devDependencies ?? {}).sort(),
  };
}

const files = listFiles(SRC);
const codeFiles = files.filter(file => CODE_EXTENSIONS.has(extensionOf(file)));
const testFiles = codeFiles.filter(file => file.endsWith('.test.ts') || file.endsWith('.test.tsx'));
const styleFiles = files.filter(file => STYLE_EXTENSIONS.has(extensionOf(file)));
const componentFiles = codeFiles.filter(file => extensionOf(file) === '.tsx');
const hookFiles = codeFiles.filter(file => /(^|[\\/])hooks[\\/]/.test(file));
const domainFiles = codeFiles.filter(file => file.includes(`${join('src', 'domain')}`));
const infrastructureFiles = codeFiles.filter(
  file => file.includes(join('src', 'infrastructure')) || file.includes(join('src', 'workers'))
);
const testUtilsFiles = codeFiles.filter(file => file.includes(join('src', 'testUtils')));
const presentationFiles = codeFiles.filter(file => file.includes(join('src', 'presentation')));

const totalLines = codeFiles.reduce((sum, file) => sum + countLines(file), 0);
const pkg = readPackage();
const date = new Date().toISOString().slice(0, 10);

const table = [
  ['Total source files', files.length],
  ['Total lines of code (non-empty)', totalLines],
  ['UI components (.tsx)', componentFiles.length],
  ['Custom hooks', hookFiles.length],
  ['Domain modules', domainFiles.length],
  ['Infrastructure & worker modules', infrastructureFiles.length],
  ['Presentation modules', presentationFiles.length],
  ['Test files', testFiles.length],
  ['Style sheets', styleFiles.length],
]
  .map(([label, value]) => `- **${label}**: \`${value}\``)
  .join('\n');

const report = `# 🤖 Architecture Overview (Auto-Generated)

> ⚡ **THIS FILE WAS AUTOMATICALLY GENERATED BY \`npm run docs:arch\`.**  
> **Project Name**: \`pixelslicer\`  
> **Version**: \`${pkg.version}\`  
> **Generated Date**: \`${date}\`

Do not edit by hand: change the source tree and re-run
\`node scripts/generate-architecture-report.mjs\`.

---

## 📌 1. Executive Summary & Metrics

This document provides an automated architectural overview of the application source code structure.

### 📊 Codebase Statistics
${table}

### 🛠️ Key Technology Stack
${[...pkg.dependencies, ...pkg.devDependencies].map(name => `- \`${name}\``).join('\n')}

---

## 🗺️ 2. Architectural Flow Diagram

\`\`\`mermaid
flowchart TD
    UI["App.tsx + presentation/components"] --> VM["EditorViewModel"]
    VM --> DOMAIN["domain (pure, unit tested)"]
    UI --> INFRA["infrastructure (canvas, zip, engines)"]
    INFRA --> DOMAIN
    UI --> WORKER["workers (OffscreenCanvas)"]
    WORKER --> INFRA
\`\`\`

---

## 📂 3. \`src/\` Directory Tree

\`\`\`text
${renderTree(files)}
\`\`\`

---

## 📋 4. Layer Breakdown

| Directory | Purpose | File Count |
| :--- | :--- | :--- |
${groupByDirectory(files)
  .map(([dir, count]) => `| \`${dir}/\` | ${describe(dir)} | ${count} |`)
  .join('\n')}

---

## ⚙️ 5. Maintainability & Code Conventions

1. **Layered architecture**: UI never contains business logic; \`domain\` never imports React or the DOM.
2. **Type safety**: strict TypeScript, \`noUnusedLocals\` and \`noUnusedParameters\` are on.
3. **Testability**: pure functions live in \`domain\` and are unit tested; browser APIs are stubbed in \`src/testUtils\`.

---
*Auto-generated by \`npm run docs:arch\` for \`pixelslicer\` ${pkg.version} on ${date}.*
`;

function describe(dir) {
  if (dir === 'src') return 'Application shell and entry point';
  if (dir === 'src/domain') return 'Pure domain logic: grid frames, video, atlas';
  if (dir.endsWith('domain/atlas')) return 'Auto-trim, pivot, bin packer, atlas layout (pure)';
  if (dir.endsWith('infrastructure/atlas')) return 'Atlas renderer, worker client, engine exporters';
  if (dir.endsWith('domain/video')) return 'Video file types, limits and validation (pure)';
  if (dir === 'src/infrastructure') return 'Browser facing services: canvas, gif, image loading';
  if (dir.endsWith('infrastructure/video')) return 'Frame extraction, grid building, upload';
  if (dir.endsWith('presentation/components')) return 'Modal components';
  if (dir.endsWith('presentation')) return 'EditorViewModel, design tokens';
  if (dir === 'src/components') return 'Gallery and thumbnail components';
  if (dir === 'src/hooks') return 'Thumbnail, upload and storage hooks';
  if (dir === 'src/i18n') return 'tr / en translation strings';
  if (dir === 'src/styles') return 'CSS variables and component styles';
  if (dir === 'src/workers') return 'Web Worker entry points';
  if (dir === 'src/testUtils') return 'Shared test fixtures (pixels, canvas)';
  if (dir === 'src/utils') return 'Scheduling helpers';
  if (dir === 'src/types') return 'Ambient module declarations';
  if (dir === 'src/assets') return 'Static assets';
  return 'Source modules';
}

writeFileSync(OUTPUT, report, 'utf8');
console.log(`Wrote ${relative(ROOT, OUTPUT)} (${files.length} files, ${totalLines} lines)`);
